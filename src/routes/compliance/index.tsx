// ─── Compliance register tab (complaints / breaches / STR) ─────
function RegisterTab({ data, loading, authToken, trpcClient, onChanged }: any) {
  const [adding, setAdding] = useState(false);
  const blank = { caseType: "COMPLAINT", title: "", description: "", severity: "MEDIUM", status: "OPEN", subjectName: "", reportedToAuthority: "", dueDate: "" };
  const [form, setForm] = useState<any>(blank);

  const save = async () => {
    if (!form.title.trim() || !form.description.trim()) { toast.error("Title and description are required."); return; }
    try {
      await trpcClient.upsertComplianceCase.mutate({
        authToken, caseType: form.caseType, title: form.title.trim(), description: form.description.trim(),
        severity: form.severity, status: form.status,
        subjectName: form.subjectName || undefined, reportedToAuthority: form.reportedToAuthority || undefined,
        dueDate: form.dueDate || undefined,
      });
      toast.success("Case saved."); setAdding(false); setForm(blank); onChanged();
    } catch (e: any) { toast.error(e?.message ?? "Could not save."); }
  };
  const setStatus = async (c: any, status: string) => {
    try {
      await trpcClient.upsertComplianceCase.mutate({ authToken, id: c.id, caseType: c.caseType, title: c.title, description: c.description, severity: c.severity, status });
      toast.success("Updated."); onChanged();
    } catch (e: any) { toast.error(e?.message ?? "Could not update."); }
  };

  if (loading) return <Spinner />;
  const cases = data?.cases ?? [];
  const s = data?.summary;

  return (
    <div>
      {s && (
        <div className="mb-5 grid grid-cols-2 gap-3 sm:grid-cols-4">
          <Count label="Open" value={s.open} color="text-rose-600" />
          <Count label="Complaints" value={s.complaints} color="text-amber-600" />
          <Count label="STRs (FIC)" value={s.strs} color="text-rose-600" />
          <Count label="Breaches" value={s.breaches} color="text-rose-600" />
        </div>
      )}

      <button onClick={() => setAdding((v) => !v)} className="mb-4 inline-flex items-center gap-1 rounded-lg bg-rose-600 px-3 py-1.5 text-sm font-semibold text-white hover:bg-rose-500"><Plus size={14} /> Log a case</button>

      {adding && (
        <div className="mb-4 grid gap-2 rounded-xl border border-rose-200 bg-rose-50/40 p-4 sm:grid-cols-2">
          <select value={form.caseType} onChange={(e) => setForm({ ...form, caseType: e.target.value })} className="rounded-md border border-gray-300 px-3 py-2 text-sm">
            {Object.entries(CASE_TYPE_LABEL).map(([k, v]) => <option key={k} value={k}>{v}</option>)}
          </select>
          <select value={form.severity} onChange={(e) => setForm({ ...form, severity: e.target.value })} className="rounded-md border border-gray-300 px-3 py-2 text-sm">
            <option value="LOW">Low</option><option value="MEDIUM">Medium</option><option value="HIGH">High</option><option value="CRITICAL">Critical</option>
          </select>
          <input value={form.title} onChange={(e) => setForm({ ...form, title: e.target.value })} placeholder="Title" className="rounded-md border border-gray-300 px-3 py-2 text-sm sm:col-span-2" />
          <textarea value={form.description} onChange={(e) => setForm({ ...form, description: e.target.value })} placeholder="Description / facts" rows={2} className="rounded-md border border-gray-300 px-3 py-2 text-sm sm:col-span-2" />
          <input value={form.subjectName} onChange={(e) => setForm({ ...form, subjectName: e.target.value })} placeholder="Subject / party (optional)" className="rounded-md border border-gray-300 px-3 py-2 text-sm" />
          <input value={form.reportedToAuthority} onChange={(e) => setForm({ ...form, reportedToAuthority: e.target.value })} placeholder="Reported to (FIC / Information Regulator / None)" className="rounded-md border border-gray-300 px-3 py-2 text-sm" />
          <div className="flex gap-2 sm:col-span-2">
            <button onClick={save} className="rounded-lg bg-rose-600 px-3 py-1.5 text-sm font-semibold text-white hover:bg-rose-500">Save</button>
            <button onClick={() => { setAdding(false); setForm(blank); }} className="rounded-lg border border-gray-300 px-3 py-1.5 text-sm">Cancel</button>
          </div>
        </div>
      )}

      {cases.length === 0 ? (
        <Empty icon={ShieldAlert} text="No cases logged. Record complaints, breaches, POPIA incidents or FIC suspicious transactions here." />
      ) : (
        <div className="space-y-2">
          {cases.map((c: any) => (
            <div key={c.id} className="rounded-xl border border-gray-200 bg-white p-4">
              <div className="flex items-start justify-between gap-3">
                <div>
                  <p className="font-semibold">{c.title}</p>
                  <p className="mt-0.5 text-xs text-gray-500">{CASE_TYPE_LABEL[c.caseType] ?? c.caseType}{c.subjectName ? ` · ${c.subjectName}` : ""}{c.reportedToAuthority ? ` · reported to ${c.reportedToAuthority}` : ""} · {new Date(c.raisedAt).toLocaleDateString("en-ZA")}</p>
                  <p className="mt-1 text-sm text-gray-600">{c.description}</p>
                </div>
                <div className="flex shrink-0 flex-col items-end gap-1">
                  <span className={`rounded-full px-2 py-0.5 text-[11px] font-medium ${CASE_SEVERITY[c.severity] ?? "bg-gray-100 text-gray-600"}`}>{c.severity}</span>
                  <span className="rounded-full bg-gray-100 px-2 py-0.5 text-[11px] font-medium text-gray-600">{c.status}</span>
                </div>
              </div>
              {!["RESOLVED", "CLOSED"].includes(c.status) && (
                <div className="mt-2 flex flex-wrap gap-2">
                  {c.status === "OPEN" && <button onClick={() => setStatus(c, "INVESTIGATING")} className="rounded-lg border border-gray-300 px-2.5 py-1 text-xs">Investigate</button>}
                  {c.caseType === "STR" && c.status !== "REPORTED" && <button onClick={() => setStatus(c, "REPORTED")} className="rounded-lg border border-amber-300 px-2.5 py-1 text-xs text-amber-700">Mark reported to FIC</button>}
                  <button onClick={() => setStatus(c, "RESOLVED")} className="rounded-lg border border-emerald-300 px-2.5 py-1 text-xs text-emerald-700">Resolve</button>
                  <button onClick={() => setStatus(c, "CLOSED")} className="rounded-lg border border-gray-300 px-2.5 py-1 text-xs">Close</button>
                </div>
              )}
            </div>
          ))}
        </div>
      )}
    </div>
  );
}

function Spinner() {
  return <div className="flex justify-center py-20"><div className="h-8 w-8 animate-spin rounded-full border-4 border-rose-500 border-r-transparent" /></div>;
}
function Empty({ icon: Icon, text }: { icon: any; text: string }) {
  return (
    <div className="rounded-xl border border-gray-200 bg-white p-12 text-center">
      <Icon className="mx-auto mb-3 text-gray-300" size={40} />
      <p className="text-sm text-gray-500">{text}</p>
    </div>
  );
}
