/** Share-class price anchor for the price collar: NAV if set, else last trade, else base price. */
async function priceAnchor(shareClass: {
  id: number;
  pricePerShare: number;
  navPerShare?: number | null;
}): Promise<number> {
  if (shareClass.navPerShare && shareClass.navPerShare > 0) return shareClass.navPerShare;
  const lastTrade = await db.shareTrade.findFirst({
    where: { shareClassId: shareClass.id },
    orderBy: { executedAt: "desc" },
    select: { pricePerShare: true },
  });
  return lastTrade?.pricePerShare ?? shareClass.pricePerShare;
}

// ─── Place Order (Buy or Sell) ─────────────────────────────────

export const placeShareOrder = baseProcedure
  .input(
    z.object({
      authToken: z.string(),
      shareClassId: z.number(),
      side: z.enum(["BUY", "SELL"]),
      quantity: z.number().int().min(1),
      pricePerShare: z.number().min(0.01),
      expiresInDays: z.number().int().min(1).max(90).optional(),
    })
  )
  .mutation(async ({ input }) => {
    const user = await getAuthenticatedUser(input.authToken);

    // KYC verification gate: Ensure investor has approved KYC documents
    const kycDocs = await db.kYCDocument.findMany({ where: { investorId: user.id } });
    const approvedTypes = kycDocs.filter((d) => d.status === "APPROVED").map((d) => d.documentType);
    const requiredKYC = ["ID_DOCUMENT", "PROOF_OF_ADDRESS", "BANK_STATEMENT"];
    const missingKYC = requiredKYC.filter((t) => !approvedTypes.includes(t as any));
    if (missingKYC.length > 0) {
      throw new TRPCError({
        code: "FORBIDDEN",
        message: `KYC verification required before trading. Missing: ${missingKYC.join(", ")}. Please upload and get approval on the KYC Compliance page.`,
      });
    }

    const shareClass = await db.shareClass.findUnique({
      where: { id: input.shareClassId },
    });
    if (!shareClass) throw new TRPCError({ code: "NOT_FOUND", message: "Share class not found" });

    // Trading controls: admin kill-switch.
    if ((shareClass as any).tradingHalted) {
      throw new TRPCError({
        code: "FORBIDDEN",
        message: `Trading in this share class is currently halted.${(shareClass as any).tradingHaltReason ? " Reason: " + (shareClass as any).tradingHaltReason : ""}`,
      });
    }

    // Price collar: reject orders whose price deviates too far from the anchor
    // (NAV, else last trade, else base price), curbing fat-finger and tape painting.
    const anchor = await priceAnchor(shareClass as any);
    const collarPct = (shareClass as any).priceCollarPct ?? 20;
    if (!priceWithinCollar(input.pricePerShare, anchor, collarPct)) {
      throw new TRPCError({
        code: "BAD_REQUEST",
        message: `Price R${input.pricePerShare.toFixed(2)} is outside the allowed ±${collarPct}% band around the reference price R${anchor.toFixed(2)} (R${(anchor * (1 - collarPct / 100)).toFixed(2)}–R${(anchor * (1 + collarPct / 100)).toFixed(2)}).`,
      });
    }

    // If selling, check that user has enough shares
    if (input.side === "SELL") {
      const holding = await db.shareHolding.findUnique({
        where: {
          shareClassId_investorId: {
            shareClassId: input.shareClassId,
            investorId: user.id,
          },
        },
      });
      // Shares committed to open sell orders AND to unsettled trade settlements
      // are reserved and may not be re-offered.
      const openSellOrders = await db.shareOrder.findMany({
        where: {
          shareClassId: input.shareClassId,
          investorId: user.id,
          side: "SELL",
          status: { in: ["OPEN", "PARTIALLY_FILLED"] },
        },
      });
      const openSettlements = await db.shareTradeSettlement.findMany({
        where: {
          shareClassId: input.shareClassId,
          sellerId: user.id,
          status: { in: ["PENDING_PAYMENT", "POP_SUBMITTED"] },
        },
        select: { quantity: true },
      });
      const committedShares =
        openSellOrders.reduce((s, o) => s + (o.quantity - o.filledQuantity), 0) +
        openSettlements.reduce((s, st) => s + st.quantity, 0);
      const available = (holding?.sharesOwned ?? 0) - committedShares;
      if (input.quantity > available) {
        throw new TRPCError({
          code: "BAD_REQUEST",
          message: `Insufficient shares. Available: ${available} (${holding?.sharesOwned ?? 0} held, ${committedShares} committed to sell orders / pending settlements)`,
        });
      }
    }

    const expiresAt = input.expiresInDays
      ? new Date(Date.now() + input.expiresInDays * 86400000)
      : null;

    const order = await db.shareOrder.create({
      data: {
        shareClassId: input.shareClassId,
        investorId: user.id,
        side: input.side,
        quantity: input.quantity,
        pricePerShare: input.pricePerShare,
        expiresAt,
      },
    });

    // ROFR: If selling, notify existing shareholders with right of first refusal
    if (input.side === "SELL") {
      const existingHolders = await db.shareHolding.findMany({
        where: {
          shareClassId: input.shareClassId,
          investorId: { not: user.id },
        },
        select: { investorId: true, sharesOwned: true },
      });

      for (const holder of existingHolders) {
        await createNotification(
          holder.investorId,
          "Right of First Refusal — Shares For Sale",
          `${user.name} is selling ${input.quantity} shares at R${input.pricePerShare.toFixed(2)}/share (total R${(input.quantity * input.pricePerShare).toFixed(2)}). As an existing shareholder, you have priority to purchase. ${expiresAt ? `Offer expires: ${expiresAt.toLocaleDateString()}.` : ""}`,
          "WARNING",
          "INVESTMENT",
          shareClass.propertyId
        );
      }
    }

    // Try to match immediately — matches create pending settlements.
    const settlements = await matchOrders(order.id);

    // Instant DvP: auto-settle each match from the buyer's wallet if funded.
    // Any match the buyer can't yet cover stays pending and settles on top-up.
    let settledCount = 0;
    for (const s of settlements) {
      try {
        const r = await autoSettleFromWallet(s.id);
        if (r.settled) settledCount += 1;
      } catch {
        /* leave pending */
      }
    }

    // Re-read for fresh (possibly SETTLED) status.
    const freshSettlements = settlements.length
      ? await db.shareTradeSettlement.findMany({
          where: { id: { in: settlements.map((s) => s.id) } },
        })
      : [];

    return {
      order,
      settlementsCreated: settlements.length,
      settledInstantly: settledCount,
      settlements: freshSettlements.map((s) => ({
        id: s.id,
        quantity: s.quantity,
        pricePerShare: s.pricePerShare,
        totalAmount: s.totalAmount,
        status: s.status,
        expiresAt: s.expiresAt,
      })),
      // Back-compat: the UI previously read tradesExecuted.
      tradesExecuted: settledCount,
    };
  });

// ─── Get Order Book ────────────────────────────────────────────

export const getOrderBook = baseProcedure
  .input(z.object({ shareClassId: z.number() }))
  .query(async ({ input }) => {
    const buyOrders = await db.shareOrder.findMany({
      where: {
        shareClassId: input.shareClassId,
        side: "BUY",
        status: { in: ["OPEN", "PARTIALLY_FILLED"] },
        OR: [{ expiresAt: null }, { expiresAt: { gt: new Date() } }],
      },
      orderBy: { pricePerShare: "desc" }, // Best buy price first
      include: { investor: { select: { id: true, name: true } } },
    });

    const sellOrders = await db.shareOrder.findMany({
      where: {
        shareClassId: input.shareClassId,
        side: "SELL",
        status: { in: ["OPEN", "PARTIALLY_FILLED"] },
        OR: [{ expiresAt: null }, { expiresAt: { gt: new Date() } }],
      },
      orderBy: { pricePerShare: "asc" }, // Best sell price first
      include: { investor: { select: { id: true, name: true } } },
    });

    // Aggregate by price level
    const buyLevels = aggregateOrderLevels(buyOrders);
    const sellLevels = aggregateOrderLevels(sellOrders);

    // Best bid/ask
    const bestBid = buyOrders[0]?.pricePerShare ?? null;
    const bestAsk = sellOrders[0]?.pricePerShare ?? null;
    const spread = bestBid && bestAsk ? bestAsk - bestBid : null;

    return {
      buyOrders: buyOrders.map(sanitizeOrder),
      sellOrders: sellOrders.map(sanitizeOrder),
      buyLevels,
      sellLevels,
      bestBid,
      bestAsk,
      spread,
    };
  });

