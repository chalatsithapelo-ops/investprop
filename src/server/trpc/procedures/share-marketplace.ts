function sanitizeOrder(order: any) {
  return {
    id: order.id,
    side: order.side,
    quantity: order.quantity,
    filledQuantity: order.filledQuantity,
    remainingQuantity: order.quantity - order.filledQuantity,
    pricePerShare: order.pricePerShare,
    status: order.status,
    investorName: order.investor?.name,
    createdAt: order.createdAt,
    expiresAt: order.expiresAt,
  };
}

function aggregateOrderLevels(orders: any[]) {
  const levels: Record<number, { price: number; quantity: number; orders: number }> = {};
  for (const o of orders) {
    const remaining = o.quantity - o.filledQuantity;
    const level = (levels[o.pricePerShare] ??= { price: o.pricePerShare, quantity: 0, orders: 0 });
    level.quantity += remaining;
    level.orders += 1;
  }
  return Object.values(levels);
}

// ═══════════════════════════════════════════════════════════════
//  Settlement (Delivery-versus-Payment)
// ═══════════════════════════════════════════════════════════════

type TxClient = Parameters<Parameters<typeof db.$transaction>[0]>[0];

/**
 * Roll back the share reservation a settlement held on its two orders. Only
 * reopens orders that are still FILLED/PARTIALLY_FILLED (a user-cancelled order
 * stays cancelled). Used when a settlement is rejected, cancelled or expires.
 */
async function releaseReservation(tx: TxClient, settlement: {
  buyOrderId: number;
  sellOrderId: number;
  quantity: number;
}): Promise<void> {
  for (const orderId of [settlement.buyOrderId, settlement.sellOrderId]) {
    const order = await tx.shareOrder.findUnique({ where: { id: orderId } });
    if (!order) continue;
    const newFilled = Math.max(0, order.filledQuantity - settlement.quantity);
    const data: any = { filledQuantity: newFilled };
    if (order.status === "FILLED" || order.status === "PARTIALLY_FILLED") {
      data.status = newFilled <= 0 ? "OPEN" : "PARTIALLY_FILLED";
    }
    await tx.shareOrder.update({ where: { id: orderId }, data });
  }
}

/**
 * Authoritative Delivery-versus-Payment settlement: moves shares seller→buyer,
 * writes both ledger legs, price history and the platform fee, and records the
 * ShareTrade. Re-checks deliverability and the buyer's ownership cap at the
 * moment of settlement. Returns the created ShareTrade.
 */
async function settleTradeDvP(tx: TxClient, settlement: any, shareClass: any): Promise<any> {
  const { buyerId, sellerId, quantity, pricePerShare, totalAmount } = settlement;

  // Seller must still hold enough (the reservation should guarantee this).
  const sellerHolding = await tx.shareHolding.findUnique({
    where: { shareClassId_investorId: { shareClassId: shareClass.id, investorId: sellerId } },
  });
  if (!sellerHolding || sellerHolding.sharesOwned < quantity) {
    throw new TRPCError({
      code: "BAD_REQUEST",
      message: `Seller can no longer deliver ${quantity} shares (holds ${sellerHolding?.sharesOwned ?? 0}). Reject this settlement.`,
    });
  }

  // Concentration cap re-check.
  const buyerHolding = await tx.shareHolding.findUnique({
    where: { shareClassId_investorId: { shareClassId: shareClass.id, investorId: buyerId } },
  });
  if (
    exceedsConcentration(
      buyerHolding?.sharesOwned ?? 0,
      quantity,
      shareClass.totalShares,
      shareClass.maxOwnershipPct
    )
  ) {
    throw new TRPCError({
      code: "BAD_REQUEST",
      message: `Settling would push the buyer above the ${shareClass.maxOwnershipPct}% ownership cap for this share class.`,
    });
  }

  // Max-investors cap re-check (only when the buyer is a brand-new holder).
  if (shareClass.maxInvestors && !buyerHolding) {
    const holderCount = await tx.shareHolding.count({
      where: { shareClassId: shareClass.id, sharesOwned: { gt: 0 } },
    });
    if (holderCount >= shareClass.maxInvestors) {
      throw new TRPCError({
        code: "BAD_REQUEST",
        message: `This share class has reached its maximum of ${shareClass.maxInvestors} investors.`,
      });
    }
  }

  // ── Securities leg: move shares seller → buyer ──
  const sellerNewBalance = sellerHolding.sharesOwned - quantity;
  // Keep the holding row at 0 rather than deleting it, preserving cost-basis history.
  await tx.shareHolding.update({
    where: { id: sellerHolding.id },
    data: { sharesOwned: sellerNewBalance },
  });

  await tx.shareLedgerEntry.create({
    data: {
      propertyId: shareClass.propertyId,
      shareClassId: shareClass.id,
      investorId: sellerId,
      transactionType: "SALE",
      shares: -quantity,
      pricePerShare,
      totalAmount,
      reference: `Market sale settled — Settlement #${settlement.id} (STT R${settlement.securitiesTransferTax.toFixed(2)})`,
      balanceAfter: Math.max(0, sellerNewBalance),
    },
  });

  const buyerNewBalance = (buyerHolding?.sharesOwned ?? 0) + quantity;
  const buyerAvgCost = buyerHolding
    ? (buyerHolding.averageCostPerShare * buyerHolding.sharesOwned + totalAmount) / buyerNewBalance
    : pricePerShare;

  await tx.shareHolding.upsert({
    where: { shareClassId_investorId: { shareClassId: shareClass.id, investorId: buyerId } },
    create: {
      propertyId: shareClass.propertyId,
      shareClassId: shareClass.id,
      investorId: buyerId,
      sharesOwned: quantity,
      averageCostPerShare: pricePerShare,
    },
    update: { sharesOwned: buyerNewBalance, averageCostPerShare: buyerAvgCost },
  });

  await tx.shareLedgerEntry.create({
    data: {
      propertyId: shareClass.propertyId,
      shareClassId: shareClass.id,
      investorId: buyerId,
      transactionType: "PURCHASE",
      shares: quantity,
      pricePerShare,
      totalAmount,
      reference: `Market purchase settled — Settlement #${settlement.id}`,
      balanceAfter: buyerNewBalance,
    },
  });

  // ── Record the executed trade + price history ──
  const trade = await tx.shareTrade.create({
    data: {
      shareClassId: shareClass.id,
      buyOrderId: settlement.buyOrderId,
      sellOrderId: settlement.sellOrderId,
      buyerId,
      sellerId,
      quantity,
      pricePerShare,
      totalAmount,
    },
  });

  await tx.sharePriceHistory.create({
    data: { shareClassId: shareClass.id, price: pricePerShare, volume: quantity },
  });

  // ── Platform fee (booked once, on settlement) ──
  try {
    const feeConfig = await getFeeConfig(tx);
    if (feeConfig.enabled) {
      await recordPlatformFee({
        tx,
        feeType: "SECONDARY_TRADE",
        sourceType: "ShareTrade",
        sourceId: trade.id,
        propertyId: shareClass.propertyId,
        baseAmount: totalAmount,
        feeBps: feeConfig.secondaryTradeFeeBps,
        description: `Secondary share trade fee — seller (${quantity} shares, Settlement #${settlement.id})`,
      });
      if (settlement.buyerFee > 0) {
        await recordPlatformFee({
          tx,
          feeType: "SECONDARY_TRADE_BUYER",
          sourceType: "ShareTrade",
          sourceId: trade.id,
          propertyId: shareClass.propertyId,
          baseAmount: totalAmount,
          feeBps: feeConfig.secondaryTradeBuyerFeeBps,
          feeAmount: settlement.buyerFee,
          description: `Secondary share trade fee — buyer (${quantity} shares, Settlement #${settlement.id})`,
        });
      }
    }
  } catch (err) {
    console.error("[platform-fees] secondary-trade fee capture failed:", err);
  }

  // ── Keep investor-facing certificates in sync with the live cap table ──
  await reconcileCertificatesForTrade(tx, {
    propertyId: shareClass.propertyId,
    sellerId,
    buyerId,
  });

  return trade;
}

// ═══════════════════════════════════════════════════════════════
//  Automatic DvP settlement from the buyer's wallet
//
//  When a buyer has funded their in-app wallet (via Paystack EFT/card), a
//  matched trade settles instantly and automatically — no manual proof-of-
//  payment review. Money and shares move together in one transaction:
//    buyer wallet −(value + STT), seller wallet +(value − fee), shares seller→buyer.
//  If the buyer has insufficient funds the settlement stays PENDING_PAYMENT and
//  auto-settles later the moment their wallet is topped up.
// ═══════════════════════════════════════════════════════════════

export async function autoSettleFromWallet(
  settlementId: number,
): Promise<{ settled: boolean; reason?: string; tradeId?: number }> {
  const settlement = await db.shareTradeSettlement.findUnique({ where: { id: settlementId } });
  if (!settlement) return { settled: false, reason: "NOT_FOUND" };
  if (!["PENDING_PAYMENT", "POP_SUBMITTED"].includes(settlement.status)) {
    return { settled: false, reason: "NOT_PENDING" };
  }
  if (settlement.expiresAt && settlement.expiresAt < new Date()) {
    return { settled: false, reason: "EXPIRED" };
  }

  const shareClass = await db.shareClass.findUnique({ where: { id: settlement.shareClassId } });
  if (!shareClass) return { settled: false, reason: "NO_SHARE_CLASS" };
  if ((shareClass as any).tradingHalted) return { settled: false, reason: "TRADING_HALTED" };

  const legs = computeSettlementCashLegs({
    totalAmount: settlement.totalAmount,
    platformFee: settlement.platformFee,
    stt: settlement.securitiesTransferTax,
    buyerFee: settlement.buyerFee,
  });

  // Fast pre-check: does the buyer have enough? (The debit is also atomically
  // guarded, so a race can only ever fail safe — never overdraw.)
  const buyerWallet = await db.wallet.findUnique({ where: { userId: settlement.buyerId } });
  if (!buyerWallet || buyerWallet.balanceCents < legs.buyerDebitCents) {
    return { settled: false, reason: "INSUFFICIENT_FUNDS" };
  }

  let tradeId: number | undefined;
  try {
    await db.$transaction(async (tx) => {
      const fresh = await tx.shareTradeSettlement.findUnique({ where: { id: settlement.id } });
      if (!fresh || !["PENDING_PAYMENT", "POP_SUBMITTED"].includes(fresh.status)) {
        throw new TRPCError({ code: "BAD_REQUEST", message: "Settlement no longer pending" });
      }
      // Cash legs — buyer pays value + STT, seller receives value − platform fee.
      await debitWallet(tx, {
        userId: settlement.buyerId,
        amountCents: legs.buyerDebitCents,
        type: "TRADE_DEBIT",
        reference: `settle-${settlement.id}-buyer`,
        description: `Payment for Settlement #${settlement.id} (${settlement.quantity} shares)`,
        settlementId: settlement.id,
      });
      await creditWallet(tx, {
        userId: settlement.sellerId,
        amountCents: legs.sellerCreditCents,
        type: "TRADE_CREDIT",
        reference: `settle-${settlement.id}-seller`,
        description: `Proceeds from Settlement #${settlement.id} (${settlement.quantity} shares)`,
        settlementId: settlement.id,
      });
      // Securities leg + share ledger + price history + platform fee + ShareTrade.
      const trade = await settleTradeDvP(tx, settlement, shareClass);
      tradeId = trade.id;
      await tx.shareTradeSettlement.update({
        where: { id: settlement.id },
        data: {
          status: "SETTLED",
          settledTradeId: trade.id,
          paymentReference: `wallet:settle-${settlement.id}`,
          paymentSubmittedAt: fresh.paymentSubmittedAt ?? new Date(),
          reviewedAt: new Date(),
          reviewNotes: "Auto-settled from buyer wallet (DvP)",
        },
      });
    });
  } catch (err) {
    // Insufficient-funds race or deliverability failure — leave the settlement
    // pending so it can be retried after a top-up or handled manually.
    return { settled: false, reason: err instanceof TRPCError ? err.message : "SETTLE_FAILED" };
  }

  await createNotification(
    settlement.buyerId,
    "Trade settled — shares delivered",
    `Settlement #${settlement.id} auto-settled from your wallet. ${settlement.quantity} shares are now in your portfolio (R${settlement.totalAmount.toFixed(2)} + R${settlement.buyerFee.toFixed(2)} platform fee + R${settlement.securitiesTransferTax.toFixed(2)} STT debited).`,
    "SUCCESS",
    "INVESTMENT",
    shareClass.propertyId,
  );
  await createNotification(
    settlement.sellerId,
    "Trade settled — funds credited",
    `Settlement #${settlement.id} is complete. R${(settlement.totalAmount - settlement.platformFee).toFixed(2)} was credited to your wallet for ${settlement.quantity} shares. You can withdraw it to your bank.`,
    "SUCCESS",
    "INVESTMENT",
    shareClass.propertyId,
  );
  await createAuditLog(0, "AUTO_SETTLE_TRADE", "ShareTradeSettlement", settlement.id, {
    tradeId,
    quantity: settlement.quantity,
    totalAmount: settlement.totalAmount,
  });
  return { settled: true, tradeId };
}

/**
 * Settle as many of a buyer's pending settlements as their wallet can cover,
 * oldest first. Called after a wallet top-up (deposit webhook / verify) so that
 * funding a wallet automatically clears outstanding trade obligations.
 */
export async function settlePendingSettlementsForBuyer(
  buyerId: number,
): Promise<{ settledCount: number }> {
  const pending = await db.shareTradeSettlement.findMany({
    where: { buyerId, status: { in: ["PENDING_PAYMENT", "POP_SUBMITTED"] } },
    orderBy: { createdAt: "asc" },
    select: { id: true },
  });
  let settledCount = 0;
  for (const p of pending) {
    const r = await autoSettleFromWallet(p.id);
    if (r.settled) settledCount += 1;
    else if (r.reason === "INSUFFICIENT_FUNDS") break; // wallet drained — stop
  }
  return { settledCount };
}

